def all_edges():
    """Every road segment once (undirected), for drawing the base map."""
    seen = set()
    edges = []
    for area, neighbors in ROAD_NETWORK.items():
        for neighbor, distance in neighbors.items():
            key = tuple(sorted((area, neighbor)))
            if key not in seen:
                seen.add(key)
                edges.append({"from": key[0], "to": key[1], "distance_km": distance})
    return edges


def find_routes(source, destination, max_routes=3, max_hops=6):
    """Depth-first search that enumerates simple (loop-free) paths between
    source and destination, keeping the shortest `max_routes` by distance.
    This models 'the application identifies all predefined routes
    connecting the selected locations' from the abstract.
    """
    if source not in ROAD_NETWORK or destination not in ROAD_NETWORK:
        return []
    if source == destination:
        return []

    found = []

    def dfs(current, path, distance, visited):
        if len(path) - 1 > max_hops:
            return
        if current == destination:
            found.append((list(path), distance))
            return
        for neighbor, dist in ROAD_NETWORK[current].items():
            if neighbor not in visited:
                visited.add(neighbor)
                path.append(neighbor)
                dfs(neighbor, path, distance + dist, visited)
                path.pop()
                visited.discard(neighbor)

    dfs(source, [source], 0.0, {source})
    found.sort(key=lambda item: item[1])
    return found[:max_routes]
